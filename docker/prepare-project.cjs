/* Prepare the real /repo project using the repository's Android environment switch. */
'use strict'

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { spawnSync } = require('node:child_process')

// Recognize the previous container's Android modules during the one-time environment switch.
const LEGACY_MARKER = path.join('.bangumi-android-dependencies', 'state.json')
const SCHEMA = 1
const PENDING_SWITCH = 'docker/.generated/android-switch.pending'
const GRADLE_MARKER = '# Generated by bangumi-entrypoint; do not edit.'
const LOCAL_MARKER = '# Generated by bangumi toolchain; do not edit.'

function fail(message) {
  throw new Error(`[bangumi-init] ${message}`)
}

function readMarker(modules) {
  const file = path.join(modules, LEGACY_MARKER)
  if (!fs.existsSync(file)) return null
  if (!fs.lstatSync(file).isFile() || fs.lstatSync(file).isSymbolicLink()) fail('Invalid dependency marker')
  const marker = JSON.parse(fs.readFileSync(file, 'utf8'))
  if (marker.schema !== SCHEMA || marker.environment !== 'android' ||
      !['installing', 'ready'].includes(marker.status)) {
    fail('Unrecognized Android dependency marker; existing dependencies were preserved')
  }
  return marker
}

function switchAndroid(repo, run, log) {
  const modules = path.join(repo, 'node_modules')
  const androidModules = path.join(repo, 'packages/android/node_modules')
  const pending = path.join(repo, PENDING_SWITCH)
  const manifest = JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8'))
  if (manifest.name === 'android') {
    const app = JSON.parse(fs.readFileSync(path.join(repo, 'app.json'), 'utf8'))
    if (!app.expo?.platforms?.includes('android') || !fs.readFileSync(path.join(repo, 'babel.config.js'), 'utf8').includes('react-native-reanimated/plugin')) {
      fail('Root Android configuration is incomplete; preserve platform backups and finish the environment switch before installing dependencies')
    }
    if (!fs.existsSync(modules) && fs.existsSync(androidModules)) fs.renameSync(androidModules, modules)
    return
  }
  const currentEnv = manifest.name === 'bangumi-pro' ? 'ios' : manifest.name
  if (!['ios', 'web'].includes(currentEnv)) fail('Unknown root environment; refusing a switch that cannot back it up')
  if (fs.existsSync(modules) && fs.lstatSync(modules).isSymbolicLink()) fail('node_modules must be a real directory')
  const legacy = fs.existsSync(modules) && readMarker(modules)
  if (fs.existsSync(modules) && fs.existsSync(path.join(repo, `packages/${legacy ? 'android' : currentEnv}/node_modules`))) {
    fail('Platform dependency caches conflict; preserve both and choose one before switching environments')
  }
  // env.js is not transactional. Do not replay its backup step against a root
  // whose manifest changed but whose Babel/app/patch restoration was interrupted.
  fs.mkdirSync(path.dirname(pending), { recursive: true })
  fs.writeFileSync(pending, `${currentEnv} -> android\n`, { flag: 'wx', mode: 0o600 })
  // Old containers combined an iOS root manifest with known Android modules.
  if (legacy) {
    fs.renameSync(modules, androidModules)
    log('[bangumi-init] Preserved existing Android modules for the native environment switch')
  }
  const result = run(process.execPath, [path.join(repo, 'packages/env.js'), 'android'], { cwd: repo, stdio: 'inherit' })
  if (result.error || result.status !== 0) fail('Android environment switch failed; existing platform caches and the pending marker were preserved')
  fs.unlinkSync(pending)
}

function configureNative({ repo, environment }) {
  const android = path.join(repo, 'android')
  const files = [
    {
      file: path.join(android, 'gradle.properties'),
      marker: GRADLE_MARKER,
      content: `${GRADLE_MARKER}
org.gradle.daemon=false
org.gradle.configureondemand=true
org.gradle.jvmargs=-Xmx2g -XX:+HeapDumpOnOutOfMemoryError -Dfile.encoding=UTF-8
org.gradle.workers.max=${environment.BANGUMI_BUILD_JOBS}
org.gradle.caching=true
org.gradle.parallel=true
android.useAndroidX=true
android.enableJetifier=true
android.buildToolsVersion=${environment.BANGUMI_ANDROID_BUILD_TOOLS}
reactNativeArchitectures=${environment.BANGUMI_ANDROID_ABI}
newArchEnabled=false
hermesEnabled=true
AsyncStorage_db_size_in_MB=100
expo.gif.enabled=true
expo.webp.enabled=true
expo.webp.animated=false
EX_DEV_CLIENT_NETWORK_INSPECTOR=true
`
    },
    {
      file: path.join(android, 'local.properties'),
      marker: LOCAL_MARKER,
      content: `${LOCAL_MARKER}
sdk.dir=${environment.ANDROID_HOME}
cmake.dir=${environment.BANGUMI_CMAKE_DIR}
`
    }
  ]
  const readOwned = item => {
    let stat
    try {
      stat = fs.lstatSync(item.file)
    } catch (error) {
      if (error.code === 'ENOENT') return undefined
      throw error
    }
    if (!stat.isFile() || stat.isSymbolicLink()) fail(`Refusing to overwrite non-regular configuration: ${item.file}`)
    const content = fs.readFileSync(item.file, 'utf8')
    if (!content.startsWith(`${item.marker}\n`)) fail(`Refusing to overwrite existing user configuration: ${item.file}`)
    return content
  }
  for (const item of files) item.current = readOwned(item)
  for (const item of files) {
    if (item.current === item.content) continue
    const temporary = `${item.file}.bangumi-${process.pid}-${crypto.randomBytes(8).toString('hex')}`
    let created = false
    try {
      fs.writeFileSync(temporary, item.content, { flag: 'wx', mode: 0o600 })
      created = true
      if (item.current === undefined) {
        try {
          fs.linkSync(temporary, item.file)
        } catch (error) {
          if (error.code !== 'EEXIST') throw error
          if (readOwned(item) !== item.content) fail(`Configuration changed while preparing it: ${item.file}`)
        }
      } else {
        const current = readOwned(item)
        if (current === item.content) continue
        if (current !== item.current) fail(`Configuration changed while preparing it: ${item.file}`)
        fs.renameSync(temporary, item.file)
        created = false
      }
    } finally {
      if (created) fs.unlinkSync(temporary)
    }
  }
}

function prepare({ repo, command = 'init', run = spawnSync, log = console.log, environment = process.env }) {
  if (!['init', 'check', 'configure'].includes(command)) fail('Usage: prepare-project.cjs [init | check | configure]')
  if (fs.existsSync(path.join(repo, PENDING_SWITCH))) fail('Previous environment switch was interrupted; inspect root configuration and platform caches before clearing docker/.generated/android-switch.pending')
  if (command === 'configure') return configureNative({ repo, environment })
  if (command === 'init') switchAndroid(repo, run, log)
  const manifest = JSON.parse(fs.readFileSync(path.join(repo, 'package.json'), 'utf8'))
  if (manifest.name !== 'android') fail('Project root is not Android; run bangumi init')
  const modules = path.join(repo, 'node_modules')
  if (command === 'check') {
    if (!fs.existsSync(modules) || !fs.statSync(modules).isDirectory()) fail('node_modules is missing; run bangumi init')
    return
  }
  // Yarn's native postinstall applies patch-package; do not run it a second time.
  const result = run('yarn', ['install', '--no-lockfile', '--non-interactive'], {
    cwd: repo, stdio: 'inherit', env: { ...environment, CI: '1', YARN_CACHE_FOLDER: environment.YARN_CACHE_FOLDER || '/home/dev/.cache/yarn' }
  })
  if (result.error) throw result.error
  if (result.signal) {
    const error = new Error(`yarn install terminated by signal ${result.signal}`)
    error.signal = result.signal
    throw error
  }
  if (result.status !== 0) {
    const error = new Error(`yarn install exited with status ${result.status}`)
    error.exitCode = result.status
    throw error
  }
  log('[bangumi-init] Android project initialized in /repo')
}

if (require.main === module) {
  try {
    if (process.env.BANGUMI_CONTAINER !== '1' || process.getuid() === 0) fail('Run as the non-root Dev Container user')
    if (process.argv.length > 3) fail('Usage: prepare-project.cjs [init | check | configure]')
    prepare({ repo: '/repo', command: process.argv[2] || 'init' })
  } catch (error) {
    console.error(error.message)
    if (error.signal) process.kill(process.pid, error.signal)
    process.exitCode = Number.isInteger(error.exitCode) && error.exitCode > 0 ? error.exitCode : 1
  }
}

module.exports = { prepare, configureNative }
